# Copy the live PostgreSQL database into the tracked snapshot (data/app.snapshot.sql).
# Run this before committing when you want the current DB state in git.
# Usage: .\scripts\db-snapshot.ps1
#
# Prefers Docker Compose service "postgres"; falls back to local pg_dump
# (PATH or Program Files\PostgreSQL\<ver>\bin) + DATABASE_URL / .env.

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'lib\postgres-cli.ps1')

$Root = Get-LoomRepoRoot
$DataDir = Join-Path $Root 'data'
$Snapshot = Join-Path $DataDir 'app.snapshot.sql'

if (-not (Test-Path $DataDir)) {
    New-Item -ItemType Directory -Path $DataDir | Out-Null
}

function Invoke-LocalPgDump([string]$PgDumpPath, [string]$Url, [string]$OutFile) {
    & $PgDumpPath --dbname=$Url --clean --if-exists --no-owner --no-acl --file=$OutFile
    if ($LASTEXITCODE -ne 0) {
        throw "pg_dump failed for DATABASE_URL ($PgDumpPath)"
    }
}

Write-Host "Writing snapshot: $Snapshot"

$Utf8NoBom = New-Object System.Text.UTF8Encoding $false

if (Test-LoomComposePostgres -RepoRoot $Root) {
    Push-Location $Root
    try {
        # Dump to a file inside the container, then copy — avoids PowerShell UTF-8 mangling of Cyrillic.
        docker compose exec -T postgres pg_dump -U loom -d loom_crm --clean --if-exists --no-owner --no-acl -f /tmp/loom-snapshot.sql
        if ($LASTEXITCODE -ne 0) {
            throw 'pg_dump via docker compose failed'
        }
        docker compose cp postgres:/tmp/loom-snapshot.sql $Snapshot
        if ($LASTEXITCODE -ne 0 -or -not (Test-Path $Snapshot)) {
            throw 'docker compose cp of snapshot failed'
        }
    } finally {
        Pop-Location
    }
} else {
    $url = Get-LoomDatabaseUrl -RepoRoot $Root
    $pgDump = Resolve-LoomPgDump
    if (-not $pgDump) {
        throw (Get-LoomPgToolsMissingMessage -ToolLabel 'pg_dump')
    }
    Write-Host "Using pg_dump: $pgDump"
    Invoke-LocalPgDump $pgDump $url $Snapshot
}

$header = @"
-- LoomCRM DB snapshot (tracked in git). Generated by scripts/db-snapshot.ps1
-- Live database is NOT in git. Restore with: .\scripts\db-restore.ps1
-- Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')

"@
$body = [System.IO.File]::ReadAllText($Snapshot, $Utf8NoBom)
if ($body -notmatch 'LoomCRM DB snapshot') {
    [System.IO.File]::WriteAllText($Snapshot, $header + $body, $Utf8NoBom)
}

Write-Host "Snapshot updated: $Snapshot"
Write-Host 'Commit it with: git add data/app.snapshot.sql'
