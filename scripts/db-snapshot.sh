#!/usr/bin/env bash
# Write a full pg_dump --clean baseline to data/app.snapshot.sql (or --out path).
# Semantics: tracked snapshot = full schema+data dump, not data-only.
#
# Usage: ./scripts/db-snapshot.sh [--out path] [--fileset production|base]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=lib/compose-cli.sh
source "$ROOT/scripts/lib/compose-cli.sh"

FILESET="${FILESET:-base}"
OUT="${OUT:-$ROOT/data/app.snapshot.sql}"
POSTGRES_USER="${POSTGRES_USER:-loom}"
POSTGRES_DB="${POSTGRES_DB:-loom_crm}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --out) OUT="$2"; shift 2 ;;
    --fileset) FILESET="$2"; shift 2 ;;
    *) echo "Unknown arg: $1" >&2; exit 2 ;;
  esac
done

log() { echo "[db-snapshot] $*"; }

mkdir -p "$(dirname "$OUT")"
log "dumping full baseline → $OUT"

loom_compose "$FILESET" exec -T postgres \
  pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" \
  --clean --if-exists --no-owner --no-acl -f /tmp/loom-snapshot.sql

tmp="$(mktemp)"
loom_compose "$FILESET" cp postgres:/tmp/loom-snapshot.sql "$tmp"

{
  echo "-- LoomCRM DB snapshot (tracked in git). Generated by scripts/db-snapshot.sh"
  echo "-- Full baseline dump (pg_dump --clean). Restore only into freshly recreated DB:"
  echo "--   ./scripts/db-recreate.sh && ./scripts/db-restore.sh"
  echo "-- Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  cat "$tmp"
} > "$OUT"
rm -f "$tmp"

log "snapshot updated: $OUT"
